/**
 * Resolve a `userProfile.language` value (`"pt"`, `"pt-PT"`, `"gu"`, or `""`/null/anything else)
 * into a [java.util.Locale] suitable for `SimpleDateFormat` / `DateTimeFormatter`. Used by the
 * History tab so weekday + month names render in the user's tongue (e.g. `dom, 07 jun, 14:30`
 * for PT) instead of always defaulting to Locale.US. The rest of the codebase still pins
 * Locale.US for Daily/Weekly headers in Reports — that's a deliberate consistency choice for
 * the report header strings ("MMM d, yyyy"); this helper exists for the per-row timeline.
 *
 * Note on PT: `Locale("pt", "PT")` is the technically-correct tag, but ICU's pt-PT data treats
 * `EEE` and `EEEE` as the same long form ("domingo"), which loses the abbreviation the History
 * row counts on. Use the language-only `Locale("pt")` so `EEE` renders as "dom." while the rest
 * of the format keeps Portuguese month/period names.
 */
fun localeForLanguage(lang: String): java.util.Locale = when (lang) {
    "pt-PT", "pt" -> java.util.Locale("pt")
    "gu" -> java.util.Locale("gu", "IN")
    else -> java.util.Locale.US
}

/**
 * Format a `timestamp` (epoch millis) for a History tab row: weekday-prefixed, 24-hour time,
 * locale-aware. Examples:
 *  - `Sun, 07 Jun, 14:30` (en-US)
 *  - `dom, 07 jun, 14:30` (pt — note ICU adds a trailing dot to abbreviated weekday/month
 *    in pt; we strip those to match Hugo's preference for `dom`/`jun` without dots)
 *
 * Centralised so food cards and activity cards stay in sync, and so future tweaks (e.g. show
 * "Today"/"Yesterday" instead of the weekday for recent entries) live in one place.
 */
fun formatHistoryDate(timestampMs: Long, language: String): String {
    val locale = localeForLanguage(language)
    val raw = java.text.SimpleDateFormat("EEE, dd MMM, HH:mm", locale)
        .format(java.util.Date(timestampMs))
    // Strip ICU's trailing dots after the abbreviated weekday and month so PT renders
    // `dom, 07 jun, 14:30` instead of `dom., 07 jun., 14:30`. Token-targeted replace
    // keeps numeric / time tokens untouched (no general "." → "" sweep).
    return raw.replace(Regex("([A-Za-zÀ-ÿ]+)\\.")) { it.groupValues[1] }
}

/**
 * Formats the "Açúcar livre" line rendered under the carbs bar on the
 * edit-meal screen. When [sourceIngredient] is non-null, it becomes a
 * "sobretudo de X" tail; otherwise the line is just the numeric breakdown.
 *
 * Example outputs (pt):
 *   "Açúcar livre: 8g / 32g · sobretudo de sumo de laranja"
 *   "Açúcar livre: 0g / 32g"
 *
 * Kept as a top-level helper (not a `tr()` map entry) because the pattern
 * carries three interpolations plus optional tail — a single `tr(...)`
 * with `%s` would push formatting quirks into every caller. Fallback for
 * unknown languages is English.
 */
fun formatFreeSugarsLine(
    freeSugarsG: Double,
    totalCarbsG: Double,
    sourceIngredient: String?,
    language: String
): String {
    val freeStr = formatGrams(freeSugarsG)
    val totalStr = formatGrams(totalCarbsG)
    return when {
        language.startsWith("pt", ignoreCase = true) -> {
            val tail = sourceIngredient
                ?.takeIf { it.isNotBlank() }
                ?.let { " · sobretudo de $it" }
                ?: ""
            "Açúcar livre: $freeStr / $totalStr$tail"
        }
        else -> {
            val tail = sourceIngredient
                ?.takeIf { it.isNotBlank() }
                ?.let { " · mostly from $it" }
                ?: ""
            "Free sugars: $freeStr / $totalStr$tail"
        }
    }
}

/** 1-decimal gram formatter that strips a trailing `.0` for compactness.
 *  E.g. `8.0 → "8g"`, `12.5 → "12.5g"`. Private to keep [formatFreeSugarsLine]
 *  a leaf helper. */
private fun formatGrams(g: Double): String {
    val rounded = (g * 10).toInt() / 10.0
    return if (rounded % 1.0 == 0.0) "${rounded.toInt()}g" else "${rounded}g"
}